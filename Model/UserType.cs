/// <summary>
/// Represents the different types of users in the PodCastWorld system.
/// </summary>
public enum UserType
{
    /// <summary>A regular listener who hears advertisements.</summary>
    Regular = 1,

    /// <summary>A premium listener with subscription access.</summary>
    Premium = 2,

    /// <summary>A podcaster who creates and hosts podcasts.</summary>
    Podcaster = 3
}
